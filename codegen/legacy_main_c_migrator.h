//
// Автоматическая раскладка main.c без маркеров USER CODE по маркерам нового
// сгенерированного main.c — без РУЧНОГО переноса пользователем (см.
// docs/implementations/reverse_import.md, "Полная перегенерация без
// USER CODE-маркеров..."). Вызывается mergeUserCodeSections (см.
// user_code_markers.cpp) только когда в существующем файле вообще нет ни
// одного маркера.
//
// Набор ID секций соответствует разметке STM32CubeMX 1:1 (пользовательское
// решение 2026-10-19 — совместимость с привычной CubeMX-раскладкой main.c).
// Правило разбора main.c:
//  - Вендорский комментарий-описание файла (привязанный к прототипу
//    SystemClock_Config, см. leadingComment) -> Header.
//  - #include, не встречающиеся в свежесгенерированном тексте -> Includes.
//  - "Голые" глобальные переменные до int main() (с инициализатором —
//    копируются как есть, без инициализатора — превращаются в
//    "extern ...;", потому что определение уже лежит в mik32_init.c) -> PV.
//  - Прототипы legacy-функций (связка для PFP, см. ниже) -> PFP (как
//    содержимое обычной секции, не отдельная "мимо маркеров" вставка).
//  - Функции, определённые ДО main() (TopLevelUnit::is_function) -> "0".
//  - Содержимое main() до цикла while, за вычетом строк вида "Имя();",
//    совпадающих с вызовом периферийной инициализации уже в новом main()
//    (значит, переинициализация избыточна — она и так уже есть) -> Init.
//  - Тело цикла while(1) {...} -> "3" (в CubeMX "WHILE" сама по себе всегда
//    пустая — обрамляет саму строку "while(1) {", весь пользовательский код
//    цикла живёт в "3").
//  - Функции, объявленные ПОСЛЕ main() и не совпадающие по имени ни с
//    SystemClock_Config, ни с одним из вызовов периферийной инициализации,
//    ни с шаблоном HAL_*_MspInit (эти три класса считаются полностью
//    замещёнными регенерацией) -> "4", как обычный рабочий код (не #if 0 —
//    иначе его не смог бы вызвать код из "3"). ИСКЛЮЧЕНИЕ внутри этой же
//    категории: функция с именем ровно "trap_handler" (единственный вектор
//    прерываний RISC-V у МИК32, подтверждено на 15 вендорных примерах с
//    прерываниями, 2026-10-19) -> IrqHandlers, не "4" — у МИК32 нет
//    отдельного it.c-файла как в CubeMX (stm32xx_it.c), поэтому вместо
//    отдельного файла это отдельная секция внутри того же main.c
//    (пользовательское решение — меньший патч вместо нового файла в шаблоне).
// PTD/PD/PM/1/SysInit/2/WHILE/Error_Handler_Debug/6 — присутствуют в шаблоне
// main.c (project_codegen.cpp) для совместимости с CubeMX, но авторазбор
// никогда в них ничего не кладёт: у вендорского кода МИК32 нет структурной
// границы, которая однозначно сопоставлялась бы именно этим секциям.
//
#ifndef MIK32_CONFIGURATOR_LEGACY_MAIN_C_MIGRATOR_H
#define MIK32_CONFIGURATOR_LEGACY_MAIN_C_MIGRATOR_H

#include <map>
#include <string>

// Возвращает {marker_id -> содержимое}, подлежащее подстановке туда же, где
// mergeUserCodeSections обычно подставляет существующие секции. Пустая карта
// означает "не удалось разобрать main() существующего файла" — вызывающий
// код (mergeUserCodeSections) в этом случае сам заворачивает existing_main_c
// целиком в безопасный #if 0 (см. komментарий там), чтобы НИЧЕГО не стереть
// даже когда авторазбор не справился.
// newly_generated_init_c — свежесгенерированный mik32_init.c, по нему
// вычисляются детерминированные имена периферийных хендлов (hi2c_0,
// htimer32_1_ch0, husart_0...), которые не совпадают с именами, которые дал
// им вендор в старом main.c (hi2c0, htimer32_channel0, husart0) — иначе
// "extern <Type> <вендорское имя>;", вставленный ниже в PV, указывал бы на
// переменную, которой не существует (линковка не проходит). Пустая строка
// допустима (просто не подменяет ничего, как раньше).
std::map<std::string, std::string> extractLegacyMainCSections(
    const std::string& newly_generated_main_c,
    const std::string& existing_main_c,
    const std::string& newly_generated_init_c = std::string());

#endif //MIK32_CONFIGURATOR_LEGACY_MAIN_C_MIGRATOR_H
