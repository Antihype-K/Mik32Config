//
// Генерический "точечный" патчер исходников для reverse-import (см.
// reverse_import_scanner.h про происхождение SourceLocation/full_line_text).
// Этот модуль не знает НИЧЕГО про периферию — ни про UART, ни про I2C, ни
// про то, что такое "baudrate". Он получает от типового маппера (см.
// mapped_block.h::FieldProvenance и serialize<Type>FieldValue у каждого
// маппера) уже готовый новый C-текст правой части присваивания и переписывает
// РОВНО ОДНУ строку РОВНО одного файла — остальной файл, включая переводы
// строк, остаётся байт-в-байт как был.
//
// Почему это отдельный модуль, а не метод внутри мапперов. Мапперы знают
// СЕМАНТИКУ поля (как сериализовать 38400 в "38400" или Parity::Even в
// "USART_PARITY_EVEN"), но ничего не знают и не должны знать про то, как
// безопасно тронуть чужой, руками написанный .c/.cpp файл (docs/сделать/
// mik32_fixed_v3 — не наш кодоген, у него нет USER CODE маркеров и нет
// гарантии, что он не менялся с момента импорта). Эта безопасность —
// отдельная, общая для всех типов периферии задача, и опирается только на
// SourceLocation + full_line_text/raw_value_text — форму, которую и
// reverse_import_scanner, и все четыре reverse_mapper'а уже гарантируют
// одинаковой.
//
// Главное защитное правило модуля: НИКОГДА не перезаписывать строку, если
// её текущее содержимое на диске не совпадает СИМВОЛ В СИМВОЛ с тем, что
// сканер увидел на момент импорта (expected_full_line_text). Файл мог
// измениться снаружи (пользователь открыл его в другом редакторе, git pull,
// параллельный запуск конфигуратора) — угадывать вместо отказа означало бы
// испортить чужой, не гитовский (в общем случае) исходник.
//
#ifndef MIK32_CONFIGURATOR_REVERSE_PATCH_WRITER_H
#define MIK32_CONFIGURATOR_REVERSE_PATCH_WRITER_H

#include <string>
#include <vector>

#include "reverse_import_scanner.h"

namespace reverse_import
{

// Одна запрошенная правка одной строки одного файла.
struct LineEditRequest
{
    SourceLocation location;          // файл + 1-based номер строки

    // Якоря — снимок состояния строки на момент импорта (то, что вернул
    // сканер как full_line_text/raw_value_text для этого присваивания).
    // Оба обязаны совпасть с текущим диском, иначе правка отклоняется —
    // см. applyLineEdit.
    std::string expected_full_line_text;
    std::string expected_value_text;

    // Новый C-текст правой части присваивания, уже построенный
    // serialize<Type>FieldValue соответствующего маппера — этот модуль его
    // не проверяет и не интерпретирует, только подставляет текстом.
    std::string new_value_text;
};

struct PatchResult
{
    bool success = false;
    std::string error;   // человекочитаемая причина отказа, если success=false
};

// Применяет одну правку к одному файлу. Алгоритм (обязателен, см. .cpp):
//  1. Прочитать location.file целиком; нет файла / нет такой строки -> отказ.
//  2. Сравнить текущую строку location.line с expected_full_line_text
//     символ в символ (без учёта терминатора строки — терминатор каждой
//     строки хранится и восстанавливается отдельно, см. .cpp). Не совпало ->
//     отказ, файл НЕ трогается.
//  3. Найти expected_value_text как подстроку правой части строки (после
//     последнего '=' и до последнего ';' в строке — то есть до заданного
//     маппером значения, не трогая хвостовой "// комментарий"). Не найдено ->
//     отказ.
//  4. Заменить ровно первое найденное вхождение на new_value_text, остальной
//     текст строки (отступы, "поле = ", ";", комментарий) не трогать.
//  5. Перезаписать файл атомарно (временный файл в той же директории +
//     переименование — тот же приём, что ProjectDocument::save,
//     см. gui/project_document.cpp/.h, ТЗ §3.2 п.1), все остальные строки
//     файла — байт-в-байт как были, включая их исходные терминаторы.
PatchResult applyLineEdit(const LineEditRequest& request);

// Batch-вариант: несколько правок одной кнопкой (несколько полей поменялись
// сразу, или одно логическое поле физически разбито на несколько строк —
// см. TIMINGR у i2c_reverse_mapper / parity+stopbits у uart_reverse_mapper).
//
// Порядок применения — как в векторе. Правки для одного и того же файла
// читают/пишут этот файл ОДИН раз (а не по разу на правку): файл грузится в
// память при первой встреченной для него правке, каждая следующая правка для
// того же файла проверяет свой якорь уже против результата ПРЕДЫДУЩИХ правок
// в этом же батче (не против диска повторно), а запись на диск происходит
// один раз после того, как весь вектор обработан.
//
// best-effort семантика: одна неудачная правка не откатывает другие уже
// применённые (в т.ч. в других файлах, а внутри одного файла — уже
// принятые ранее в этом же батче правки остаются в силе и будут записаны).
// Файл, для которого НИ ОДНА правка не прошла, вообще не переписывается на
// диск (оставаясь идентичным исходному по содержимому, хотя мог быть
// прочитан — чтение не портит файл).
//
// Возвращает вектор той же длины и в том же порядке, что requests — по
// одному PatchResult на каждый элемент, для показа в GUI "что применилось,
// что нет и почему".
std::vector<PatchResult> applyLineEdits(const std::vector<LineEditRequest>& requests);

} // namespace reverse_import

#endif //MIK32_CONFIGURATOR_REVERSE_PATCH_WRITER_H
